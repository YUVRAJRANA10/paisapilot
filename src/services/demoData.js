// Sum of October expenses per category, derived from the transactions above
const spentIn = (categoryId, month = '2024-10') =>
  DEMO_TRANSACTIONS
    .filter(t => t.type === 'expense' && t.categoryId === categoryId && t.date.startsWith(month))
    .reduce((sum, t) => sum + t.amount, 0)

